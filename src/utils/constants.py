import math


BOHR_TO_ANGSTROM = 0.52917721092
ANGSTROM_TO_BOHR = 1.0 / BOHR_TO_ANGSTROM

HARTREE_TO_KCAL_MOL = 627.51
KCAL_MOL_TO_HARTREE = 1.0 / HARTREE_TO_KCAL_MOL
HARTREE_TO_KJMOL = 2625.5
KJMOL_TO_HARTREE = 1.0 / HARTREE_TO_KJMOL
HARTREE_TO_EV = 27.2114
HARTREE_TO_CM1 = 219474.0

# 2022 CODATA: m_e = 5.485799090441e-4 u, hence 1 u in electron masses.
# The previous value (1838.6836605) was the neutron/electron mass ratio.
ATOMIC_MASS_UNIT_TO_ELECTRON_MASS = 1822.88848628
# Backward-compatible name used throughout the codebase. The tabulated values
# in atomic_masses.py are relative atomic masses, numerically expressed in u.
ATOMIC_MASS_GMOL_TO_AU = ATOMIC_MASS_UNIT_TO_ELECTRON_MASS
FS_TO_AU_TIME = 41.341105
AU_SPEED_OF_LIGHT = 137.035999074

CM1_TO_AU_FREQUENCY = AU_SPEED_OF_LIGHT / (1.0e8 * ANGSTROM_TO_BOHR)
CM1_TO_AU_ANGULAR_FREQUENCY = CM1_TO_AU_FREQUENCY * (2.0 * math.pi)
AU_ANGULAR_FREQUENCY_TO_CM1 = 1.0 / CM1_TO_AU_ANGULAR_FREQUENCY

R_GAS_KJMOL_PER_K = 8.3144598 / 1000.0
R_GAS_HARTREE_PER_K = R_GAS_KJMOL_PER_K * KJMOL_TO_HARTREE
