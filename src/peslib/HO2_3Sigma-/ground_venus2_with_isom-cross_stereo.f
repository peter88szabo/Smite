      COMMON/PRLIST/T,V,H,TIME,NTZ,NC,KRANOD ,NT
      COMMON/QPDOT/Q(150),PDOT(150)
      COMMON/PQDOT/P(150),QDOT(150),W(50)
      COMMON BQ(150),BP(150),TABLE(2100)
C        RUNGE-KUTTA-GILL INTEGRATION
C
  501 L=1
      CALL PARTI
  502 DO 503 I=1,NI
      RDUM=RAA1*TIME/1440.
      Q(I)=Q(I)+RDUM*QDOT(I)
      P(I)=P(I)+RDUM*PDOT(I)
      BQ(I)=QDOT(I)
  503 BP(I)=PDOT(I)
      CALL PARTI
  504 DO 505 I=1,NI
      RDUM=RA1*TIME/1440.
      Q(I)=Q(I)+(QDOT(I)-BQ(I))*RDUM
      P(I)=P(I)+(PDOT(I)-BP(I))*RDUM
      BQ(I)=(RA2*QDOT(I)-RA3*BQ(I))
  505 BP(I)=(RA2*PDOT(I)-RA3*BP(I))
      CALL PARTI
  506 DO 507 I=1,NI
      RDUM=RB1*TIME/1440.
      Q(I)=Q(I)+(QDOT(I)-BQ(I))*RDUM
      P(I)=P(I)+(PDOT(I)-BP(I))*RDUM
      BQ(I)=(RB2*QDOT(I)-RB3*BQ(I))
  507 BP(I)=(RB2*PDOT(I)-RB3*BP(I))
      CALL PARTI
  508 DO 509 I=1,NI
      Q(I)=Q(I)+(QDOT(I)*RC1-BQ(I)*RC2)*TIME/1440.
  509 P(I)=P(I)+(PDOT(I)*RC1-BP(I)*RC2)*TIME/1440.
      CALL PARTI
  510 I=L*NID
      DO 511 K=1,NI
      M=I+K
      N=M+NI
      TABLE(M)=PDOT(K)
  511 TABLE(N)=QDOT(K)
      L=L+1
      IF(L.LT.7)GO TO 502
CXP   GO TO 401
      RETURN
      END
