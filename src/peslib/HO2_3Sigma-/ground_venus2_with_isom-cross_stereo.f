      IF(DUM1.LT.ENJ)GO TO 1
      RMIN=RMIN+0.002D0
      RMAX=RZ
    2 RMAX=RMAX+0.002D0
      DUM1=DUM/RMAX**2+FHARM*(RMAX-RZ)**2/2.0D0
      IF(DUM1.LT.ENJ)GO TO 2
      RMAX=RMAX-0.002D0
      RETURN
      END
