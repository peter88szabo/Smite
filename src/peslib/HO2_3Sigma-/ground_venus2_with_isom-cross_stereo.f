C
      RANOD=ZBQLU01(DUMMY)
      DUM=TWOPI*RANOD
      SCOOR= SIN(DUM)
      EWANT=ENON*C1
      EFACT= SQRT(D(1)*EWANT)
      DELR=- LOG((D(1)-EWANT)/(D(1)+EFACT*SCOOR))
      DELR=DELR/B(1)
      RWANT=RMZ(1)+DELR
      RETURN
