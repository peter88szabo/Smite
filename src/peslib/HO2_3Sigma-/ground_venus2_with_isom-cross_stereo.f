      SUBROUTINE enrot(AMS,EROT)
      IMPLICIT REAL*8(A-H,O-Z)
      COMMON/PQDOT/P(150),QDOT(150),W(50)
      COMMON/WASTE/QQ(150),PP(150),WX,WY,WZ,L(25),NAM
      COMMON/CONSTN/C1,C2,C3,C4,C5,C6,C7,PI,HALFPI,TWOPI
      COMMON/INERT/UXX,UXY,UXZ,UYY,UYZ,UZZ,AIXX,AIXY,AIXZ,AIYY,
     *AIYZ,AIZZ
      DIMENSION r1(3),r2(3),r3(3),r4(3),p1(3),p2(3),ams(4)
CXCCa
C        CALCULATE ANGULAR MOMENTUM COMPONENTS PERPENDICULAR TO THE          
C        MOLECULAR AXIS  AND THE CORRESPONDING ROTATIONAL ENERGY
C         *** for linear triatomic molecules ***
C        CODE TAKEN FROM G. C. SCHATZ
C          in the triatomic molecule A-B-C
C           the order of atoms must be A(1), B(3), C(2)
CXCCz
      EROT=0.0D0
      j=l(1)
      ama=w(j)
      j=l(3)
      amb=w(j)
      j=l(2)
      amc=w(j)
      am1=ama+amc
      amac=ama*amc/am1
      ambc=amb*am1/(amb+am1)
CXCC     calculation of Euler angles    
      do 10 i=1,3
      jsa=3*l(1)-3+i
      jsc=3*l(2)-3+i
      jsb=3*l(3)-3+i
      r2(i)=qq(jsa)-qq(jsc)
      r1(i)=qq(jsb)-(ama*qq(jsa)+amc*qq(jsc))/am1
      p2(i)=amac*(pp(jsa)/ama - pp(jsc)/amc)
      p1(i)=ambc*(pp(jsb)/amb -(pp(jsa)+pp(jsc))/am1)
  10  continue
      r3(1)=r2(2)*r1(3) - r2(3)*r1(2)
      r3(2)=r2(3)*r1(1) - r2(1)*r1(3)
      r3(3)=r2(1)*r1(2) - r2(2)*r1(1)
      sr2=r2(1)**2 + r2(2)**2 + r2(3)**2
      sr1=r1(1)**2 + r1(2)**2 + r1(3)**2
      cp= sqrt(r3(1)**2 + r3(2)**2 + r3(3)**2)
      dp=r1(1)*r2(1) + r1(2)*r2(2) + r1(3)*r2(3)
      r2xp= sqrt(sr2)
      r1xp=dp/r2xp
      r1zp= sqrt(sr1 - dp*dp/sr2)
      do 20 is=1,3
  20  r4(is)=(r1(is) - dp*r2(is)/sr2)/r1zp
      th= acos(r4(3))
      phi= atan(r4(2)/r4(1))
      if(r4(1) .lt. 0) phi=phi+4.0d0* atan(1.d0)
      bot=r2(3)/r2xp
      psi= atan(r3(3)/cp/bot)
      if(bot .gt. 0.d0) psi=psi+4.d0* atan(1.d0)
CXCC     transformation from body-fixed Cartesian coordinates 
CXCC        to rotating axes coord.s
      call rotsa(r3,r1,phi,th,psi,2)
      call rotsa(r4,r2,phi,th,psi,-2)
      call rotsa(r1,p1,phi,th,psi,-2)
      call rotsa(r2,p2,phi,th,psi,-2)
      fsj1=r3(2)*r1(3)-r3(3)*r1(2) + r4(2)*r2(3)-r4(3)*r2(2)
      fsj2=r3(3)*r1(1)-r3(1)*r1(3) + r4(3)*r2(1)-r4(1)*r2(3)
      fsj3=r3(1)*r1(2)-r3(2)*r1(1) + r4(1)*r2(2)-r4(2)*r2(1)
      sjrot= sqrt(fsj2**2 + fsj3**2)/c7
C        CALCULATE ROTATIONAL ENERGY
      sjrot2=sjrot*sjrot
        amom= 1004285.65 - 1.051696 * sjrot + .2206831 *
     *  sjrot2 - .3438847d-5 * sjrot2*sjrot + 9.151958d-8 *sjrot2*sjrot2
      EROT=sjrot2/2.d0/amom*627.104d0
c     erot=sjrot2/2.d0/amom*627.52
      sjrot=sjrot*c7
      ams(3)=fsj1
      ams(2)=fsj2
      ams(1)=fsj3 
      ams(4)= sqrt(fsj1*fsj1+sjrot*sjrot) 
CXCXW...WRITE(6,*) 'enrot,  ',erot ,ams(4)/c7       
CXCXW...WRITE(6,931) (ams(i)/c7,i=1,4)
CX 931  format('am enrot',4e17.8)
      RETURN
      END
      SUBROUTINE rotsa(xb,xs,phi,th,psi,io)
CX      ROTATION BY EULER ANGLES
      IMPLICIT REAL*8(A-H,O-Z)
      dimension xb(3),xs(3),fm(3,3)
      if(io.lt.0) go to 15
      sph= sin(phi)
      cph= cos(phi)
      sth= sin(th)
      cth= cos(th)
      sps= sin(psi)
      cps= cos(psi)
      fm(1,1)=cps*cth*cph - sps*sph
      fm(1,2)=cps*cth*sph + sps*cph
      fm(1,3)=-cps*sth
      fm(2,1)=-cph*cth*sps - cps*sph
      fm(2,2)=-sps*cth*sph + cps*cph
      fm(2,3)=sps*sth
      fm(3,1)=sth*cph
      fm(3,2)=sth*sph
      fm(3,3)=cth
  15  if(iabs(io) .eq. 2) go to 16
C     BF to SF
      do 10 i=1,3
      xs(i)=0.d0
      do 10 j=1,3
  10  xs(i)=xs(i) + fm(j,i)*xb(j)
      return
C     SF to BF
  16  do 20 i=1,3
      xb(i)=0.d0
      do 20 j=1,3
  20  xb(i)=xb(i) + fm(i,j)*xs(j)
      return
      end
