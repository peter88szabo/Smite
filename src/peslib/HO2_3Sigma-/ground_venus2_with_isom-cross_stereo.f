      SUBROUTINE ROTEN(AM,AI,TROT,EROT,NROT,NLIN)
      IMPLICIT REAL*8(A-H,O-Z)
      COMMON/CONSTN/C1,C2,C3,C4,C5,C6,C7,PI,HALFPI,TWOPI
      COMMON/SELTB/QZ(150),RANOD,KRAND,NSELT,NSFLAG
C
C        THE ARRAY SIZES OF THE RELEVANT CALLING ARGUEMENTS ARE
C        DEFINED IN COMMON BLOCKS IN SUBROUTINE SELECT.
C
C                   ROTEN:             SELECT:
C
C                   AM(4)              AMA(4)  AMB(4)
C                   AI(3)              AI(3)   BI(3)
C
      DIMENSION AM(4),AI(3)
C
CXCCa    NROT=0 , CHOOSE ROTATIONAL ENERGY FROM A THERMAL
C        NROT<=0 , CHOOSE ROTATIONAL ENERGY FROM A THERMAL
C                 DISTRIBUTION BY ASSUMING A SYMMETRIC TOP.
C                 FARADAY DISCUSSIONS 55, 93(1973).
C                 Z IS THE SYMMETRY AXIS, WITH IX=IY.
C        NROT=1 , ROTATIONAL ENERGY ABOUT EACH AXIS EQUALS RT/2.
C        NLIN=0 , MOLECULE IS NONLINEAR
C        NLIN=1 , MOLECULE IS LINEAR
C        NOTE: , A LINEAR MOLECULE MUST LIE ALONG THE Z-AXIS.
C        NOTE: , LZMAX**2 = 10*2*AI(3)*C5*TROT
C
      EROT=0.0D0
      AM(3)=0.0D0
      TEMP=C5*TROT
CXCCa IF(NROT.EQ.0) GO TO 2
      IF(NROT.LE.0) GO TO 2
CXCCz
      N=3-NLIN
      DO 1 I=1,N
      AM(I)= SQRT(AI(I)*TEMP)
      RANOD=ZBQLU01(DUMMY)
      IF(RANOD.LT.0.5D0) AM(I)=-AM(I)
    1 CONTINUE
      EROT=FLOAT(N)*TEMP/2.0D0/C1
      GO TO 4
C
    2 CONTINUE
      IF(NLIN.EQ.1)GO TO 3
      ALZMAX= SQRT(20.0D0*AI(3)*TEMP)
      RANOD=ZBQLU01(DUMMY)
      AM(3)=RANOD*ALZMAX
      DUM= EXP(-AM(3)**2/2.0D0/AI(3)/TEMP)
      RANOD=ZBQLU01(DUMMY)
      IF(RANOD.GT.DUM) GO TO 2
      RANOD=ZBQLU01(DUMMY)
      IF(RANOD.GT.0.5D0) AM(3)=-AM(3)
      EROT=AM(3)**2/AI(3)
    3 RANOD=ZBQLU01(DUMMY)
      DUM= SQRT(AI(1)*AI(2))
      AL= SQRT(AM(3)**2-2.0D0*DUM*TEMP*   LOG(1.0D0-RANOD))
      DUM= SQRT(AL**2-AM(3)**2)
      RANOD=ZBQLU01(DUMMY)
      AM(1)=DUM* SIN(TWOPI*RANOD)
      AM(2)=DUM* COS(TWOPI*RANOD)
      EROT=(AM(1)**2/AI(1)+AM(2)**2/AI(2)+EROT)/2.0D0/C1
    4 CONTINUE
      RETURN
      END
