      DUM=RMASS*RZ**2
      DUM=C7/2.0D0/TWOPI/DUM
      DUM1= SQRT(FHARM/RMASS)/TWOPI
      DUM2=FLOAT(N)+0.50D0
      DUM3=FLOAT(J*(J+1))
      ENJ=TWOPI*C7*(DUM1*DUM2+DUM*DUM3+6.0D0*DUM**2*DUM2*DUM3/DUM1
     *-4.0D0*DUM**3*DUM3**2/DUM1**2)
