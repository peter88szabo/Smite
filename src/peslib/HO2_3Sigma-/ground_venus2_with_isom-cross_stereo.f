      A=ENJ-D-DUM1*DUM3
      DUM1=(1.0D0-3.0D0/2.0D0/B/RZ)*2.0D0/DUM/B/RZ
      BB=2.0D0*D-DUM1*DUM3
      DUM1=(1.0D0-3.0D0/B/RZ)/2.0D0/DUM/B/RZ
      C=-D+DUM1*DUM3
      RETURN
      END
