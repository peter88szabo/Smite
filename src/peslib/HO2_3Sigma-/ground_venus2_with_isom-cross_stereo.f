C        SUBROUTINE CENMAS CALCULATES THE CENTER OF MASS MOMENTA AND COORDINATES
C
      SUBROUTINE CENMAS(WT,QCM,VCM,N)
      IMPLICIT REAL*8(A-H,O-Z)
      COMMON/QPDOT/Q(150),pdot(150)
      COMMON/PQDOT/P(150),QDOT(150),W(50)
      COMMON/WASTE/QQ(150),PP(150),WX,WY,WZ,L(25),NAM
      DIMENSION QCM(3),VCM(3)
C
C        CENTER OF MASS COORDINATES AND MOMENTA ARE STORED IN
C        ARRAYS QQ AND PP
C
      DO 1 I=1,3
      VCM(I)=0.0D0
    1 QCM(I)=0.0D0
C
      DO 2 I=1,N
      J=L(I)
      J3=3*J
      J2=J3-1
      J1=J2-1
      VCM(1)=VCM(1)+P(J1)
      VCM(2)=VCM(2)+P(J2)
      VCM(3)=VCM(3)+P(J3)
      QCM(1)=QCM(1)+W(J)*Q(J1)
      QCM(2)=QCM(2)+W(J)*Q(J2)
      QCM(3)=QCM(3)+W(J)*Q(J3)
    2 CONTINUE
C
      DO 4 I=1,3
      VCM(I)=VCM(I)/WT
    4 QCM(I)=QCM(I)/WT
C
      DO 5 I=1,N
      J=L(I)
      J3=3*J
      J2=J3-1
      J1=J2-1
      PP(J1)=P(J1)-W(J)*VCM(1)
      PP(J2)=P(J2)-W(J)*VCM(2)
      PP(J3)=P(J3)-W(J)*VCM(3)
      QQ(J1)=Q(J1)-QCM(1)
      QQ(J2)=Q(J2)-QCM(2)
      QQ(J3)=Q(J3)-QCM(3)
    5 CONTINUE
C
      RETURN
      END
