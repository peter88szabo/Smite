      SUBROUTINE ANGVEL(N)
      IMPLICIT REAL*8(A-H,O-Z)
      COMMON/PQDOT/P(150),QDOT(150),W(50)
      COMMON/WASTE/QQ(150),PP(150),WX,WY,WZ,L(25),NAM
C
      DO 2 I=1,N
      J=L(I)
      J3=3*J
      J2=J3-1
      J1=J2-1
      P(J1)=P(J1)-(QQ(J3)*WY-QQ(J2)*WZ)*W(J)
      P(J2)=P(J2)-(QQ(J1)*WZ-QQ(J3)*WX)*W(J)
      P(J3)=P(J3)-(QQ(J2)*WX-QQ(J1)*WY)*W(J)
      PP(J1)=P(J1)
      PP(J2)=P(J2)
      PP(J3)=P(J3)
    2 CONTINUE
      RETURN
      END
