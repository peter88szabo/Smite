      SUBROUTINE INITMO(D,B,RZ,ENJ,DUM3,A,BB,C,RMASS,VN,RJ,EROT)
cx  allow non-integer vibr. and rot. quantum numbers
      IMPLICIT REAL*8(A-H,O-Z)
