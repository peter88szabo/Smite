      SUBROUTINE LMEXCT(RWANT)
      IMPLICIT REAL*8 (A-H,O-Z)
      COMMON/LMODEB/ENON,NONI,NONJ,JFLAG
      COMMON/MORSEB/RMZ(100),B(100),D(100),N2J(100),N2K(100),
     *CM1(4),CM2(4),CM3(4),CM4(4)
      COMMON/PQDOT/P(150),QDOT(150),W(50)
      COMMON/QPDOT/Q(150),pdot(150)
      COMMON/CONSTN/C1,C2,C3,C4,C5,C6,C7,PI,HALFPI,TWOPI
C
C        STRETCH MORSE BOND #1 BY PULLING ATOM #1
C        UNTIL CH LOCAL ENERGY EQUALS ENON
CX      not tested
      QX=Q(1)-Q(4)
      QY=Q(2)-Q(5)
      QZ=Q(3)-Q(6)
      R= SQRT(QX*QX + QY*QY +QZ*QZ)
      RX=QX/R
      RY=QY/R
      RZ=QZ/R
      WAPB=W(1)+W(2)
      WA=W(1)/WAPB
      WB=W(2)/WAPB
      WU=W(1)*W(2)/WAPB
      PX=WB*P(1)-WA*P(4)
      PY=WB*P(2)-WA*P(5)
      PZ=WB*P(3)-WA*P(6)
      T=(PX*PX + PY*PY +PZ*PZ)/WU/2.0D0
      V= EXP(-B(1)*(R-RMZ(1)))
      V=D(1)*(V*V-2.0D0*V+1.0D0)
      ECH=(V+T)/0.04184D0
      JFLAG=0
      IF( ABS(ECH-ENON)/ENON.GT.0.0005)GO TO 2
      JFLAG=1
      RETURN
    2 CONTINUE
C
C         CHOOSE MORSE OSCILLATOR COORDINATES AND
C         MOMENTA RANDOMLY AS DESCRIBED IN
C         Ref.: J. CHEM. PHYS.,63,2214(1975)
C
      DX=(RWANT-R)*RX
      DY=(RWANT-R)*RY
      DZ=(RWANT-R)*RZ
      Q(1)=Q(1)+DX
      Q(2)=Q(2)+DY
      Q(3)=Q(3)+DZ
      QX=Q(1)-Q(4)
      QY=Q(2)-Q(5)
      QZ=Q(3)-Q(6)
      R= SQRT(QX*QX + QY*QY + QZ*QZ)
      V= EXP(-B(1)*(R-RMZ(1)))
      V=D(1)*(V*V-2.0D0*V+1.0D0)
      VCH=V/0.04184D0
      TWANT=ENON-VCH
      TWANT=TWANT*0.04184D0
C
C        ADD APPROPRIATE KINETIC ENERGY TO THE CH
C        LOCAL MODE SO THAT ENON=ECH
C
