      ENJ=DUM3/2.0D0/DUM
      EROT=ENJ
c      WRITE(27,*) DUM,DUM1,DUM2,DUM3,ENJ
      ENJ=ENJ+DUM1*DUM2
      ENJ=ENJ-DUM1**2*DUM2**2/4.0D0/D
