      RMASS=W(L(1))*W(L(2))/(W(L(1))+W(L(2)))
c      WRITE(27,*) W(L(1)),W(L(2)),L(1),L(2),VN,RJB
      DUM=RMASS*RZ**2
      DUM1=B* SQRT(2.0D0*D/RMASS)
