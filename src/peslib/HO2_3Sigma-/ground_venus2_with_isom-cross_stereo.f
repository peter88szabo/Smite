      SUBROUTINE ROTATE(N)
      IMPLICIT REAL*8(A-H,O-Z)
      COMMON/QPDOT/Q(150),pdot(150)
      COMMON/PQDOT/P(150)
      COMMON/WASTE/QQ(150),PP(150),WX,WY,WZ,L(25)
      COMMON/SELTB/QZ(150),RANOD,KRAND,NSELT,NSFLAG,NACT
      COMMON/CONSTN/C1,C2,C3,C4,C5,C6,C7,PI,HALFPI,TWOPI
C
C        THIS SUBROUTINE RANDOMLY ROTATES THE MOLECULE ABOUT ITS
C        CENTER OF MASS BY EULER'S ANGLES.  CENTER OF MASS
C        COORDINATES(QQ) AND MOMENTA(PP) ARE PASSED FROM SUBROUTINES
C        CENMAS AND ANGVEL THROUGH COMMON BLOCK WASTE.
C
      RANOD=ZBQLU01(DUMMY)
      PHI=TWOPI*RANOD
      RANOD=ZBQLU01(DUMMY)
      CSTHTA=2.0D0*RANOD-1.0D0
      RANOD=ZBQLU01(DUMMY)
      CHI=TWOPI*RANOD
      THTA= ACOS(CSTHTA)
      SNTHTA= SIN(THTA)
      SNPHI= SIN(PHI)
      CSPHI= COS(PHI)
      SNCHI= SIN(CHI)
      CSCHI= COS(CHI)
      RXX=CSTHTA*CSPHI*CSCHI-SNPHI*SNCHI
      RXY=-CSTHTA*CSPHI*SNCHI-SNPHI*CSCHI
      RXZ=SNTHTA*CSPHI
      RYX=CSTHTA*SNPHI*CSCHI+CSPHI*SNCHI
      RYY=-CSTHTA*SNPHI*SNCHI+CSPHI*CSCHI
      RYZ=SNTHTA*SNPHI
      RZX=-SNTHTA*CSCHI
      RZY=SNTHTA*SNCHI
      RZZ=CSTHTA
      DO 1 I=1,N
      J=3*L(I)
      Q(J-2)=QQ(J-2)*RXX+QQ(J-1)*RXY+QQ(J)*RXZ
      Q(J-1)=QQ(J-2)*RYX+QQ(J-1)*RYY+QQ(J)*RYZ
      Q(J)  =QQ(J-2)*RZX+QQ(J-1)*RZY+QQ(J)*RZZ
      P(J-2)=PP(J-2)*RXX+PP(J-1)*RXY+PP(J)*RXZ
      P(J-1)=PP(J-2)*RYX+PP(J-1)*RYY+PP(J)*RYZ
      P(J)  =PP(J-2)*RZX+PP(J-1)*RZY+PP(J)*RZZ
    1 CONTINUE
      RETURN
      END
