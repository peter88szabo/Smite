C
C         CALCULATE FOR THE EXTENSION OF PARTICULAR
C         BOND LENGTH RANDOMLY BY SEMICLASSICAL PRES-
C         CRIPTION OF MILLER'S EQUATION.
C         NOTICE THAT J=0
CX      not tested
      SUBROUTINE LMODE(RWANT)
      IMPLICIT REAL*8(A-H,O-Z)
      COMMON/LMODEB/ENON,NONI,NONJ,JFLAG
      COMMON/CONSTN/C1,C2,C3,C4,C5,C6,C7,PI,HALFPI,TWOPI
      COMMON/MORSEB/RMZ(100),B(100),D(100),N2J(100),N2K(100),
